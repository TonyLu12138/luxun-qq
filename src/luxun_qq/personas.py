# -*- coding: utf-8 -*-
"""人格注册表：不同「回答角色」集中管理，配置里按 id 切换。

设计要点：
    * 每个人格只负责**语气与视角**，三步思考的 JSON 协议是统一的（见 engine）。
    * 人格可以通过 ``candidate_plan`` 调整三个候选的**排序与性格分工**，
      因此"男方视角"这种要求不需要改引擎，只需换人格。
    * 新增人格只需在下面加一个 ``Persona`` 并注册进 ``PERSONAS``。
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Optional

__all__ = ["Persona", "PERSONAS", "get_persona", "DEFAULT_PERSONA_ID"]


@dataclass
class Persona:
    """一个回答角色。"""

    id: str
    label: str
    #: 完整人格提示词（会被放进 system prompt 最前面）
    prompt: str
    #: 三个候选的性格分工描述，供提示词与展示使用
    candidate_plan: list[tuple[str, str]] = field(default_factory=list)
    #: 额外硬性要求（会追加到提示词里）
    extra_rules: list[str] = field(default_factory=list)
    #: 语气阶段生成后的自检清单：让模型自查，不合格就重写
    self_check: list[str] = field(default_factory=list)
    #: 风格样本是否仍然参与（情感大师这类需要更强角色设定时可关掉）
    use_style_sample: bool = True

    def candidate_labels(self) -> list[str]:
        return [name for name, _ in self.candidate_plan] or ["一锐", "一软", "一退"]

    def plan_text(self) -> str:
        """把候选分工渲染成提示词片段。"""
        if not self.candidate_plan:
            return ""
        lines = [f"- 候选{i}（{name}）：{desc}"
                 for i, (name, desc) in enumerate(self.candidate_plan, 1)]
        return "\n".join(lines)


