PERSONAS: dict[str, Persona] = {
    LUXUN_PERSONA.id: LUXUN_PERSONA,
    EMOTION_MASTER_MALE_PERSONA.id: EMOTION_MASTER_MALE_PERSONA,
}

DEFAULT_PERSONA_ID = EMOTION_MASTER_MALE_PERSONA.id


def get_persona(persona_id: Optional[str] = None) -> Persona:
    """按 id 取人格；未知 id 回退到默认人格（不抛异常，保证服务可用）。"""
    pid = (persona_id or "").strip()
    if not pid:
        return PERSONAS[DEFAULT_PERSONA_ID]
    return PERSONAS.get(pid) or PERSONAS[DEFAULT_PERSONA_ID]
