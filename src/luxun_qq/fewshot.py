# -*- coding: utf-8 -*-
"""Few-shot 示例：给 7B 级模型看的"三个候选到底长什么样"。

为什么需要它：抽象描述（"要冷峻、要反语"）对小模型收效有限，
给出**具体例子**才能把语气、句长、三个候选的差异同时钉住。
这些例子也顺带示范了"对话方向不要搞反"——谁在加班、谁在回话要分清。
"""

FEWSHOT_BLOCK = """\
## 三个候选长什么样（照着这个手感写，不要照抄内容）

对方说「今天又加班到这个点，你睡了吗」（注意：是**他在加班**）：
[1] 一锐｜这个点还在耗着，公司该给你发两块碑。先去洗把脸，我在这儿。
[2] 一软｜我醒着。挑今天最堵心的那一件讲，讲完就睡，剩下的交给明天。
[3] 一退｜世上的班是加不完的，人的血是有限的。今晚先把自己留下来。

对方说「在吗？借我两千块钱急用」：
[1] 一锐｜数字、日期、用途，你给我这三样，我就给你答复。含糊的账最伤人。
[2] 一软｜钱可以再挣，话说死了就难圆。你先说清要多少、什么时候还。
[3] 一退｜我愿意帮，但只帮我担得起的数目。丑话在前，情分在后。

对方说「我最近好烦，感觉做什么都没意思」：
[1] 一锐｜烦就烦着，不必急着好起来。人不是机器，没有义务随时在线。
[2] 一软｜那就先什么都别做。今天剩下的时间归你，不归任何人。
[3] 一退｜我陪你耗着。你不用说话，出声也行。

### 反面对照（这样写就是失败）

- 「还在忙碌啊，辛苦了，早点休息吧」← 客服腔，不是锐评。
- 「还没睡就多穿点」← 张冠李戴，把对方的处境安到自己身上。
- 「你早睡早起身体好」← 长辈说教，且答非所问。
- 三条候选只是把同一句话换几个词 ← 没有真实差异。

## 语气要点

1. **分清谁在说话。** 对方讲的是他自己的事（他加班、他烦、他要借钱），
   不要反问"你睡了吗"，不要把处境安到自己头上。
2. **不要"辛苦了""注意身体""早点休息""加油""别太累"这类客套。**
3. **一锐**要有一次反转或归谬：先顺着对方说，再轻轻一推，推出荒诞感。
   可以刻薄，但刀口对准事理（那个加班安排、那笔糊涂账），不对准对方本人。
   好例子：「你是不是忘了我这儿可没办公室？」「比我还晚的是不是月亮？」
4. **一软**不比一锐暖，只是不给刀；同样清醒，留一步余地。
5. **一退**极短，一到两句，常常只回应情绪、不回应内容。
6. 三条读起来必须能立刻分辨出区别；能互相替换就是失败。
"""


#: 用于自检/文档：示例里出现的"禁用客套词"
BANNED_PHRASES = ("辛苦了", "注意身体", "早点休息", "加油", "别太累",
                  "要开心", "抱抱", "么么")


# --------------------------------------------------------------------------- #
# 两段式生成：先自由写候选（语气优先），再结构化（格式优先）
# --------------------------------------------------------------------------- #

VOICE_SYSTEM = """\
你是一个说话像鲁迅的人：冷峻、克制、爱用反语和归谬，句子短，不写套话。

现在对方发来一条消息，你要写 3 条回复给他。规则：

1. **先看清谁在说话。** 对方说的是他自己的处境，不是你的。
   他加班就是他在加班，不要反问"你睡了吗"，不要把他的话安到自己身上。
2. 三条必须真的不同：
   - 第 1 条最锋利：一次反转或归谬，可以刻薄，但刀口对准事理，不对准他本人。
   - 第 2 条同样清醒，但不给刀，留一步余地。
   - 第 3 条极短，一到两句，往往只回应情绪、不回应内容。
3. **禁止出现**：辛苦了、注意身体、早点休息、加油、别太累、你要开心。
   要表达关心就用具体的事说。
4. 句子要短，像我平时发消息那样，可以有换行。

只输出 3 行，每行格式必须是：
1||候选内容
2||候选内容
3||候选内容
不要任何其他文字、不要解释、不要引号。
"""

STRUCT_SYSTEM = """\
你把一段已有的回复内容整理成严格 JSON。**绝对不要改写、增删、润色候选文字**，
候选必须逐字保留原文。

只输出一个 JSON 对象，结构如下：
{
  "step1_read": {"literal": "对方字面在说什么", "intent": "他真正想要什么",
                 "facts": ["从消息里读出的事实"]},
  "step2_emotion": {"emotion": "情绪标签", "intensity": 0.0,
                    "need": "他此刻的情绪需求", "risk": "回复时的雷区"},
  "step3_strategy": {"strategy": "整体策略名", "tone": "腔调说明",
                     "avoid": ["要避免的"],
                     "candidates": [{"text": "第1条原文", "why": "为什么这样回"},
                                    {"text": "第2条原文", "why": "..."},
                                    {"text": "第3条原文", "why": "..."}]}
}
intensity 必须是 0 到 1 之间的小数（例如 0.7）。
不要代码块，不要额外文字。
"""


def parse_voice_output(text: str) -> list[str]:
    """解析「1||内容」格式的三条候选。

    只认**编号行**。早期版本在编号不足时会拿非编号行凑数，结果把模型的
    解释句、复述句也当成候选，质量自检因此形同虚设——所以这里刻意严格：
    宁可判为不足 3 条（触发重生成），也不凑数。
    """
    import re as _re

    out: list[str] = []
    # 编号分隔：1|| / 1| / 1. / 1、/ 1） / 1： 等
    pat = _re.compile(r"^\s*[\[（(]?\s*(\d)\s*[\]）)]?\s*(?:\|\||[|、.．)）:：])\s*(.+)$")
    for ln in (text or "").splitlines():
        ln = ln.strip()
        if not ln:
            continue
        m = pat.match(ln)
        if not m:
            continue
        body = m.group(2).strip().strip('"“”\'')
        # 去掉模型偶尔附上的标签，如「一锐：」
        body = _re.sub(r"^(一锐|一软|一退|锐|软|退)\s*[:：]\s*", "", body).strip()
        if body:
            out.append(body)
    return out[:3]


# 判定"平庸/客服腔"的信号：命中即认为语气不合格，需要重生成
LAZY_PATTERNS = (
    "早点休息", "早点睡", "早些休息", "注意身体", "多喝热水", "多穿点",
    "辛苦了", "别太累", "加油", "要开心", "抱抱", "好好休息",
    "换个角度看", "想开点", "都会好的", "一切都会好",
)

# 一锐必须满足的最小信息量：太短且无具体指向的，视为没写出来
_MIN_SHARP_CHARS = 6


def score_candidates(cands: list[str], incoming: str = "",
                     persona: object = None) -> tuple[float, list[str]]:
    """给三条候选打分（0~1，越高越好），并返回问题清单。

    这是对"7B 模型输出不稳定"的工程化兜底：与其反复调 prompt 求稳，
    不如**生成后判分，不合格就带批评重生成**——成本只在必要时付出。

    刻意严格：早期版本几乎人人满分，等于没有把关。现在把几类真实失败模式
    都算成扣分项（客套腔、一锐没内容、答非所问、复述对方原话、三条雷同、
    英文混入、落点太冷）。

    Args:
        persona: 可选 Persona；不同人格的合格线不同（例如情感大师不许冷落对方）
    """
    issues: list[str] = []
    if len(cands) < 3:
        return 0.0, [f"候选不足 3 条（{len(cands)}）"]

    def norm(s: str) -> str:
        return "".join(ch for ch in s if ch not in "，。！？、；：…~ \n\t")

    # 人格：是否鲁迅腔（决定"一锐"这类规则是否适用）
    pid = getattr(persona, "id", "") or ""

    score = 1.0

    # 1) 客套 / 平庸词
    hits = [p for c in cands for p in LAZY_PATTERNS if p in c]
    if hits:
        uniq = sorted(set(hits))
        issues.append("含客套词：" + "、".join(uniq))
        score -= 0.35 * len(uniq)

    # 2) 英文混入（情感大师场景下很出戏，必须扣）
    import re as _re

    for i, c in enumerate(cands, 1):
        words = _re.findall(r"[A-Za-z]{3,}", c)
        # 允许常见缩写/品牌，其余视为混入
        allow = {"ok", "OK", "Ok"}
        bad = [wd for wd in words if wd not in allow]
        if bad:
            issues.append(f"候选{i}混入英文：" + "、".join(bad[:3]))
            score -= 0.25

    # 3) 一锐/首条必须有实质内容（太短 = 没写出来）
    sharp = norm(cands[0])
    if len(sharp) < _MIN_SHARP_CHARS:
        issues.append(f"第1条过短（{len(sharp)} 字），没有写出观点")
        score -= 0.5

    # 4) 不能复述对方原话充数
    inc = norm(incoming or "")
    if inc and len(inc) >= 4:
        for i, c in enumerate(cands, 1):
            nc = norm(c)
            if nc and (nc == inc or (len(nc) >= 6 and nc in inc)):
                issues.append(f"候选{i}只是复述对方原话")
                score -= 0.4

    # 5) 三条必须真的不同
    ns = [norm(c) for c in cands]
    if len(set(ns)) < 3:
        issues.append("候选去重后不足 3 条")
        score -= 0.5
    else:
        for i in (1, 2):
            if ns[i] and len(ns[i]) >= 3 and ns[i] in ns[0]:
                issues.append(f"候选{i + 1}是第1条的子串")
                score -= 0.15

    # 6) 三条不能都短到没信息量
    if all(len(x) <= 4 for x in ns):
        issues.append("三条候选都过短，没有信息量")
        score -= 0.3

    # 7) 最后一条不宜过长（留白感）
    if len(ns[2]) > 40:
        issues.append("第3条过长，失去留白感")
        score -= 0.1

    # 8) 空泛建议（换环境/想开点之类）
    for i, c in enumerate(cands, 1):
        if ("换个" in c and "环境" in c) or "想开" in c:
            issues.append(f"候选{i}是空泛建议")
            score -= 0.2

    # 9) 人格专属：情感大师不许"落点太冷"（对方明显有情绪时只回一个字）
    if pid == "emotion_master_male":
        emotional = any(w in (incoming or "") for w in
                        ("累", "烦", "难过", "生气", "委屈", "被骂", "哭",
                         "不开心", "郁闷", "崩溃", "难受"))
        if emotional:
            # 第 3 条允许短，但三条里至少要有两条带温度
            warm = sum(1 for c in cands if len(norm(c)) >= 6)
            if warm < 2:
                issues.append("对方有明显情绪，但候选普遍太短、显得冷落")
                score -= 0.35

    return max(0.0, min(1.0, score)), sorted(set(issues))



